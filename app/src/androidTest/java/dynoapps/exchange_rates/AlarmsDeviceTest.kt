package dynoapps.exchange_rates

import android.app.ActivityManager
import android.content.Context
import android.content.Intent
import androidx.lifecycle.Lifecycle
import androidx.test.core.app.ActivityScenario
import androidx.test.core.app.ApplicationProvider
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import dynoapps.exchange_rates.alarm.Alarm
import dynoapps.exchange_rates.data.CurrencyType
import dynoapps.exchange_rates.model.rates.IRate
import dynoapps.exchange_rates.service.RatePollingService
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith
import java.util.concurrent.CountDownLatch
import java.util.concurrent.TimeUnit

@RunWith(AndroidJUnit4::class)
class AlarmsDeviceTest {

    private val context: Context = ApplicationProvider.getApplicationContext()
    private val instrumentation = InstrumentationRegistry.getInstrumentation()

    /** Exercises the Room code generated by kapt against the real on-device database. */
    @Test
    fun alarmDatabase_roundTrip() {
        val dao = AppDatabase.getInstance(context).alarm()
        val alarm = testAlarm()
        alarm.id = dao.insert(alarm).blockingGet()

        val stored = dao.list().blockingGet().single { it.id == alarm.id }
        assertEquals(alarm.`val`, stored.`val`)
        assertEquals(alarm.isAbove, stored.isAbove)
        assertEquals(alarm.sourceType, stored.sourceType)
        assertEquals(alarm.rateType, stored.rateType)

        assertEquals(1, dao.deleteById(alarm.id).blockingGet())
    }

    /**
     * With an active alarm, leaving the app must start the foreground polling service. This is the
     * path Android 12+ restricts, so it is checked on a real device.
     */
    @Test
    fun leavingApp_withActiveAlarm_startsPollingService() {
        val repository = App.getInstance().provideAlarmsRepository()
        val saved = CountDownLatch(1)
        var alarm: Alarm? = null
        instrumentation.runOnMainSync {
            repository.saveAlarm(testAlarm()) {
                alarm = it
                saved.countDown()
            }
        }
        assertTrue("Alarm was not saved", saved.await(10, TimeUnit.SECONDS))

        try {
            ActivityScenario.launch(LandingActivity::class.java).use { scenario ->
                assertEquals(Lifecycle.State.RESUMED, scenario.state)
                instrumentation.uiAutomation.executeShellCommand("input keyevent KEYCODE_HOME").close()

                assertTrue("RatePollingService did not start", waitFor(15_000) { isPollingServiceRunning() })
                Screenshots.take("background_notification")
            }
        } finally {
            context.stopService(Intent(context, RatePollingService::class.java))
            alarm?.let { AppDatabase.getInstance(context).alarm().deleteById(it.id).blockingGet() }
            instrumentation.runOnMainSync { repository.refreshAlarms() }
        }
    }

    /** An alarm that never fires: USD/TRY below 1 on Altın.in, a source enabled by default. */
    private fun testAlarm() = Alarm().apply {
        `val` = 1f
        isAbove = false
        sourceType = CurrencyType.ALTININ
        rateType = IRate.USD
    }

    @Suppress("DEPRECATION") // Still returns the caller's own services.
    private fun isPollingServiceRunning(): Boolean {
        val manager = context.getSystemService(ActivityManager::class.java)
        return manager.getRunningServices(Int.MAX_VALUE)
            .any { it.service.className == RatePollingService::class.java.name }
    }

    private fun waitFor(timeoutMillis: Long, condition: () -> Boolean): Boolean {
        val deadline = System.currentTimeMillis() + timeoutMillis
        while (System.currentTimeMillis() < deadline) {
            if (condition()) return true
            Thread.sleep(250)
        }
        return condition()
    }
}
